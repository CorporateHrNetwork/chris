const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "../..");
const read = file => fs.readFileSync(path.join(root, file), "utf8");

test("Zermatt offer composer uses employee profile and authoritative policy", () => {
  const component = read("src/pages/documents/ZermattOfferLetterComposer.jsx");
  const terms = read("backend/src/services/zermattOfferEntitlementService.js");
  const page = read("src/pages/documents/ZermattEmploymentResources.jsx");
  assert.ok(page.includes("<ZermattOfferLetterComposer />"));
  assert.ok(component.includes("/api/zermatt/offer-terms/"));
  assert.ok(component.includes("annual_leave_days: terms?.annualLeaveDays"));
  assert.ok(component.includes("year_end_bonus_clause: terms?.yearEndBonusClause"));
  assert.ok(terms.includes("resolveEffectiveEmploymentLevel"));
  assert.ok(terms.includes("leaveEntitlementAllocation.findFirst"));
  assert.ok(terms.includes("leaveEntitlementMatrixRule.findFirst"));
  assert.ok(terms.includes("expatriate ? 45"));
  assert.ok(terms.includes("If approved by management"));
});

test("offer contains all fourteen sections and editable HR fields with print draft guard", () => {
  const c = read("src/pages/documents/ZermattOfferLetterComposer.jsx");
  for (let i = 1; i <= 14; i++) assert.ok(c.includes('["' + i + "."), "Missing section " + i);
  assert.ok(c.includes("authorized_signatory_name"));
  assert.ok(c.includes("gross_monthly_salary"));
  assert.ok(c.includes("offer_reference_number"));
  assert.ok(c.includes("work_location_address"));
  assert.ok(c.includes("Print / Save Draft PDF"));
  assert.ok(c.includes("Complete all required fields"));
  assert.ok(c.includes("Powered and generated by CHRiS"));
  assert.ok(c.includes("/zrt-logo.jpeg"));
  assert.ok(c.includes("values.branch_name"));
  assert.ok(c.includes("Printing does not approve"));
});

test("employee offer-terms endpoint retains tenant and branch authorization", () => {
  const c = read("backend/src/routes/zermattOfferTermsRoutes.js");
  assert.ok(c.includes("requireAuth"));
  assert.ok(c.includes("requireAnyPermission"));
  assert.ok(c.includes("employee.locationId"));
  assert.ok(c.includes("activeLocationId"));
});
